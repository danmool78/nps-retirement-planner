def render_html(svg) -> str:
    """안내 카드 HTML. svg: ui.svg 함수(아이콘)."""
    out = []
    for title, icon, items in SECTIONS:
        cards = []
        for field, where, links, tip in items:
            link_html = "".join(
                f'<a href="{html.escape(url)}" target="_blank" rel="noopener noreferrer">{svg("link", 13)}'
                f'{html.escape(label)}</a>' for label, url in links)
            cards.append(
                f'<div class="gcard"><div class="gf">{html.escape(field)}</div>'
                f'<div class="gw">{html.escape(where)}</div>'
                + (f'<div class="gl">{link_html}</div>' if links else "")
                + (f'<div class="gt">{svg("info", 13)}<span>{html.escape(tip)}</span></div>' if tip else "")
                + "</div>")
        out.append(f'<div class="gsec"><div class="gh">{svg(icon, 17)}<span>{html.escape(title)}</span></div>'
                   f'<div class="ggrid">{"".join(cards)}</div></div>')
    return "".join(out)
